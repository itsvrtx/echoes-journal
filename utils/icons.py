from pathlib import Path
from PySide6.QtGui import QPixmap, QIcon
from PySide6.QtCore import Qt

def get_logo(size: int = 48) -> QPixmap:
    logo_path = Path(__file__).parent.parent / "assets" / "logo.svg"
    
    if not logo_path.exists():
        print(f"Warning: Logo not found at {logo_path}")
        return QPixmap()
    
    pixmap = QPixmap(str(logo_path))
    return pixmap.scaledToHeight(size, mode=Qt.TransformationMode.SmoothTransformation)


def get_logo_icon(size: int = 48) -> QIcon:
    pixmap = get_logo(size)
    return QIcon(pixmap)

